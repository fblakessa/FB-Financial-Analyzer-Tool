open_issue "xlsx package has two unfixed high-severity advisories" \
"Defect found while building.

\`xlsx@0.18.5\` in apps/shell/package.json carries two high-severity advisories
on the npm registry, with no patched version published there because SheetJS
moved distribution to its own CDN:

- Prototype pollution
- Regular expression denial of service (ReDoS)

Low risk today, because the only input is a committed fixture workbook. It
matters before real upload traffic: parsing operator-supplied files is the
module's whole purpose, and the upload route already accepts arbitrary .xlsx.

Options: pull the SheetJS CDN build, pin a different reader, or parse the
workbook without a general-purpose xlsx library."

open_issue "No route-handler or component test coverage" \
"Gap found while building.

All 77 tests are pure lib/ logic: engine, determinism, validate, scorecard,
to-csv, plus Sample Tracker's sort. Untested:

- every route handler under apps/shell/src/app/api/apps/operator-lens
- every component under apps/shell/src/apps/operator-lens/components

This matches Sample Tracker, which has no route or component tests either, so
it is a repo-wide convention rather than an Operator Lens omission. Worth
deciding before more routes land. The upload POST is the highest-value target:
its validation paths were verified by hand with curl, not by a committed test."

open_issue "Review and Confirm gate is specified but not enforced" \
"Defect found while building. This is the most significant gap in the module.

SPEC section 3 makes a human Review and Confirm step mandatory between
extraction and analysis, and states that no route may bypass it. The screen
does not exist.

Both paths that create an engagement set the confirmation fields themselves:

- apps/shell/prisma/seed.ts sets \`figuresConfirmedAt\` directly
- the upload POST in
  apps/shell/src/app/api/apps/operator-lens/projects/[projectSlug]/engagements/route.ts
  sets \`figuresConfirmedAt\` and \`figuresConfirmedByName\` at upload time

So nothing today enforces that a human saw a figure before it was analysed. It
is defensible for a workbook the operator filled in themselves, and no route
bypasses the gate only because there is no other ingestion path yet. It stops
being defensible the moment model extraction lands, because that is exactly the
risk the gate exists to catch: a misread figure flowing silently into a finding
a consultant repeats to a client.

Build the editable review grid (SPEC section 8.3) and make confirmation an
explicit operator action before extraction ships."

open_issue "gapText is presentation data stored in engine output" \
"Defect found while building.

lib/engine.ts writes a \`gapText\` field (for example \`\"541bps\"\`) into a
flag's \`computedValues\` JSON, duplicating its \`gapBps\` sibling in
pre-formatted form.

Consequences:

- the findings UI filters \`*Text\` keys out at render time to avoid showing a
  redundant row, which is a display-layer workaround for a data problem
- the CSV export ships stored JSON verbatim, so \`gapText\` appears in the
  \`computed_values_json\` column

Remove it from the engine and reseed. \`computedValues\` should hold the figures
a rule used, not strings formatted for a screen."

open_issue "Only one benchmark industry and size band is seeded" \
"Gap found while building.

\`consumer-retail-v1\` covers exactly one combination: \`CONSUMER_RETAIL\` at
\`\$25M - \$100M\`, in USD, as of 2026-02-01, sample size 8. Any other
combination gets trend and coherence flags only, reported as unbenchmarked
rather than as a pass.

The upload screen populates its dropdowns from the distinct values in
\`BenchmarkStat\`, so an operator cannot select a combination with no data.
That is correct behaviour, but it currently means one choice each.

Related and worth recording: the peer set runs \$270M to \$565M in revenue
against a \$38.2M demo subject, 7x to 15x larger. They are joined on the
\`\$25M - \$100M\` band because otherwise nothing matches and the benchmark
rules never evaluate, so that band label is a convenience rather than a size
match. The mismatch is written into the benchmark \`source\` string so it
renders on screen. Genuinely \$38M US-listed specialty retailers have largely
been delisted or acquired, so real size-matched comparables need private
company data."

open_issue "reset.sh has the Windows path bug that was fixed in run.sh" \
"Defect found while building.

scripts/reset.sh line 5 uses bare \`pwd\`:

    REPO=\"\$(cd \"\$(dirname \"\${BASH_SOURCE[0]}\")/..\" && pwd)\"
    export DATABASE_URL=\"\${DATABASE_URL:-file:\$REPO/dev.db}\"

Under Git Bash on Windows \`pwd\` returns \`/c/Users/...\`, which Prisma
resolves literally against the drive root and silently creates a phantom
\`C:\\\\c\\\\Users\\\\...\\\\dev.db\` instead of using the repo's database. The
symptom is a reset that appears to succeed while the running app reads a
different file.

scripts/run.sh was fixed for this: it derives a native path with
\`pwd -W\` and falls back to \`\$REPO\` on Linux and macOS. Apply the same fix
to reset.sh.

Note: scripts/reset.ps1 is NOT affected. It converts backslashes correctly,
the same way run.ps1 does, and is the tested Windows path."

