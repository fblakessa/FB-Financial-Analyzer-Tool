#!/usr/bin/env bash
# One-shot helper: opens the 25 Operator Lens issues via the GitHub CLI.
#
# The 19 items from docs/operator-lens/PLAN.md section 6, plus 6 defects and
# gaps found while building the module.
#
# Requires the GitHub CLI, authenticated:
#   winget install --id GitHub.cli
#   gh auth login
#
# Run from the repo root:
#   bash scripts/open-issues.sh
#
# Safe to read before running; it only calls `gh issue create`. It is NOT
# idempotent: running it twice creates duplicates.

set -euo pipefail

command -v gh >/dev/null || { echo "gh not found. Install the GitHub CLI first."; exit 1; }
gh auth status >/dev/null 2>&1 || { echo "gh is not authenticated. Run: gh auth login"; exit 1; }

created=0

open_issue () {
  local title="$1" body="$2"
  local url
  url="$(gh issue create --title "$title" --body "$body")"
  created=$((created + 1))
  printf '%-4s %s\n     %s\n' "[$created]" "$title" "$url"
}

